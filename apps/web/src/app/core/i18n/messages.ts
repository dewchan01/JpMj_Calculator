const patterns = Object.entries(zhTW)
  .filter(([key]) => key.includes('{'))
  .map(([key, value]) => {
    const fields: string[] = [];
    const escaped = key
      .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
      .replace(/\\\{(\w+)\\\}/g, (_, name: string) => {
        fields.push(name);
        return name === 'tile' ? '([^·]+?)' : '(.+?)';
      });
    return { regex: new RegExp(`^${escaped}$`), fields, value };
  });
export function translate(source: string | null | undefined, language: Language): string {
  if (!source) return '';
  if (language === 'en') return source;
  if (zhTW[source]) return zhTW[source];
  for (const { regex, fields, value } of patterns) {
    const match = regex.exec(source);
    if (match)
      return fields.reduce(
        (text, field, i) =>
          text.replaceAll(
            `{${field}}`,
            ['seat', 'field', 'wind'].includes(field)
              ? (zhTW[match[i + 1]] ?? match[i + 1])
              : match[i + 1],
          ),
        value,
      );
  }
  if (source.includes(' · '))
    return source
      .split(' · ')
      .map((part) => translate(part, language))
      .join('・');
  return source;
}
